import java.util.*;
public class overlbydatatypes{
    public static int sum(int a , int b){
        return a+b;
    }
    public static float sum(float a , float b){
        return a+b;
    }
    public static void main(String args[]){
        System.out.println(sum(4,5));
        System.out.println(sum(6.5f,8.3f));
    }
}