import java.util.*;
public class switch_stat{
    public static void main(String args[]){
        int a = 3;

        switch(a){
            case 1:
            System.out.println("monday");
            break;

            case 2:
            System.out.println("tueday");
            break;

            case 3:
            System.out.println("wed");
            break;

            default:
                System.out.println("thu");

        }
    }
}